#!/usr/bin/env python3
"""Give each corridor's background UEs a position near their own eNodeB.

Why this is needed at all: Simu5G's BackgroundUe has a StationaryMobility
submodule with no default position tied to its parent cell. Left unset, a
background UE is placed without reference to the eNodeB whose resources it is
supposed to consume. On a playground sized to a real 20 km corridor that puts
it tens of km away, and the first SINR computation aborts the run:

    <!> Error: LOS rural macrocell path loss model is valid for d < 10000 m
        -- in module ...bgTrafficGenerator[0].bgUE[0].generator, at t=0s

That is why enabling background traffic needs this file and not just a
`startTimeUl`. See docs/CORRECTIONS_2026-10.md C13 for how the whole load axis
came to be void.

RADIUS is deliberately the SAME for every corridor. A radius derived from each
corridor's own site density would make a background UE's path loss -- and so
the resource blocks it consumes for a fixed offered rate -- a function of
corridor geometry, which would confound corridor with load in exactly the
comparison this study makes. A fixed box keeps "20 background UEs per cell"
meaning the same thing in c08 as in c14.

Checked before choosing 1000 m: across c08..c14 the smallest eNodeB coordinate
is 2000 m and the smallest headroom to constraintAreaMax is 2000 m, so a
+/-1000 m box lands inside the constraint area in every corridor without
clamping, and is two orders inside the 10 km model limit.

Idempotent: rewrites a delimited block, so it can be re-run after the corridor
fragments are regenerated by tools/opencellid_towers.py.

Usage: gen_bgue_placement.py [corridor.ini ...]     (default: all cNN.ini)
"""
import glob
import os
import re
import sys

RADIUS_M = 1000.0

BEGIN = '# >>> BEGIN generated by tools/gen_bgue_placement.py -- do not edit'
END = '# <<< END generated by tools/gen_bgue_placement.py'

ENB_RE = re.compile(
    r'^\*\.eNodeB\[(\d+)\]\.mobility\.initial([XY]) = ([0-9.]+)m\s*$', re.M)


def coords(text):
    """eNodeB index -> (x, y), from the fragment's own position lines."""
    got = {}
    for idx, axis, val in ENB_RE.findall(text):
        got.setdefault(int(idx), {})[axis] = float(val)
    out = {}
    for idx in sorted(got):
        if 'X' in got[idx] and 'Y' in got[idx]:
            out[idx] = (got[idx]['X'], got[idx]['Y'])
    return out


def block(enbs, area):
    lines = [
        BEGIN,
        '# Background UEs sit within +/-%.0f m of their own eNodeB. Without'
        % RADIUS_M,
        '# this they are placed off-geometry and the RMa path loss model asserts.',
    ]
    maxx, maxy = area
    for idx, (x, y) in enbs.items():
        lo_x, hi_x = x - RADIUS_M, x + RADIUS_M
        lo_y, hi_y = y - RADIUS_M, y + RADIUS_M
        # Should never trigger given the headroom check in the docstring, but a
        # regenerated fragment could move a site; fail loudly rather than place
        # a UE outside the playground.
        if lo_x < 0 or lo_y < 0 or (maxx and hi_x > maxx) or (maxy and hi_y > maxy):
            raise SystemExit(
                'eNodeB[%d] at (%.1f, %.1f) leaves no room for a %.0f m box '
                'inside the constraint area (max %s, %s) -- lower RADIUS_M'
                % (idx, x, y, RADIUS_M, maxx, maxy))
        pre = '*.eNodeB[%d].cellularNic.bgTrafficGenerator[0].bgUE[*].mobility' % idx
        lines.append('%s.initialX = uniform(%.1fm, %.1fm)' % (pre, lo_x, hi_x))
        lines.append('%s.initialY = uniform(%.1fm, %.1fm)' % (pre, lo_y, hi_y))
    lines.append(END)
    return '\n'.join(lines) + '\n'


def area_of(text):
    def one(name):
        m = re.search(r'constraintArea%s = ([0-9.]+)m' % name, text)
        return float(m.group(1)) if m else None
    return one('MaxX'), one('MaxY')


def main():
    args = sys.argv[1:]
    if args:
        paths = args
    else:
        here = os.path.dirname(os.path.abspath(__file__))
        pat = os.path.join(here, '..', 'simulations', 'corridorpop', 'c[0-9][0-9].ini')
        paths = sorted(glob.glob(pat))
    if not paths:
        print('no corridor fragments found', file=sys.stderr)
        return 1

    for p in paths:
        with open(p) as fh:
            text = fh.read()
        enbs = coords(text)
        if not enbs:
            print('%-10s no eNodeB positions -- skipped' % os.path.basename(p))
            continue
        declared = re.search(r'^\*\.numEnb = (\d+)\s*$', text, re.M)
        if declared and int(declared.group(1)) != len(enbs):
            print('%-10s numEnb=%s but %d positioned -- skipped'
                  % (os.path.basename(p), declared.group(1), len(enbs)),
                  file=sys.stderr)
            continue

        new = block(enbs, area_of(text))
        stripped = re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END) + r'\n',
                          '', text, flags=re.S)
        if not stripped.endswith('\n'):
            stripped += '\n'
        with open(p, 'w') as fh:
            fh.write(stripped + new)
        print('%-10s %d eNodeBs placed' % (os.path.basename(p), len(enbs)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
